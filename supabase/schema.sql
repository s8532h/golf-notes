-- Golf Notes cloud sync schema
-- Run manually in Supabase SQL Editor. This file is NOT applied automatically.
-- Uses the signed-in user's auth.uid(); never put a service_role key in the client.

create table if not exists public.golf_notes (
  user_id uuid primary key references auth.users(id) on delete cascade,
  notes jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.golf_memos (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  source_id text not null,
  title text not null default '',
  body text not null default '',
  category text,
  original_category text,
  tag text,
  memo_date text,
  next_action text,
  raw_payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id, source_id)
);

create table if not exists public.golf_rounds (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  source_id text not null,
  played_at date,
  course_name text,
  total_score integer,
  putts integer,
  ob_count integer,
  fairway_hits integer,
  gir_count integer,
  memo text,
  next_action text,
  raw_payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id, source_id)
);

create table if not exists public.golf_user_data (
  user_id uuid primary key references auth.users(id) on delete cascade,
  records jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now()
);

