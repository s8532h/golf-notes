-- Atomic ID-based merge for non-round/non-memo records, including deletion tombstones.
create or replace function public.golf_notes_merge_user_data(p_records jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_user_id uuid := auth.uid();
  v_records jsonb;
  v_item jsonb;
  v_existing jsonb;
  v_id text;
  v_in_stamp text;
  v_old_stamp text;
begin
  if v_user_id is null then
    raise exception 'Authentication required';
  end if;
  if p_records is null or jsonb_typeof(p_records) <> 'array' then
    raise exception 'p_records must be a JSON array';
  end if;

  select records into v_records
    from public.golf_user_data
    where user_id = v_user_id
    for update;
  v_records := coalesce(v_records, '[]'::jsonb);

  for v_item in select value from jsonb_array_elements(p_records)
  loop
    if jsonb_typeof(v_item) <> 'object' then continue; end if;
    v_id := coalesce(v_item->>'id', v_item->>'source_id');
    if v_id is null or length(v_id) = 0 then continue; end if;

    select value into v_existing
      from jsonb_array_elements(v_records)
      where coalesce(value->>'id', value->>'source_id') = v_id
      limit 1;

    if v_existing is null then
      v_records := v_records || jsonb_build_array(v_item);
    else
      v_in_stamp := coalesce(v_item->>'updatedAt', v_item->>'updated_at', v_item->>'deletedAt', '');
      v_old_stamp := coalesce(v_existing->>'updatedAt', v_existing->>'updated_at', v_existing->>'deletedAt', '');
      if v_in_stamp >= v_old_stamp then
        select coalesce(jsonb_agg(case
          when coalesce(value->>'id', value->>'source_id') = v_id then v_item
          else value end order by ordinality), '[]'::jsonb)
        into v_records
        from jsonb_array_elements(v_records) with ordinality;
      end if;
    end if;
    v_existing := null;
  end loop;

  insert into public.golf_user_data(user_id, records, updated_at)
    values (v_user_id, v_records, now())
  on conflict (user_id) do update
    set records = excluded.records, updated_at = excluded.updated_at;

  return v_records;
end;
$$;

revoke all on function public.golf_notes_merge_user_data(jsonb) from public;
grant execute on function public.golf_notes_merge_user_data(jsonb) to authenticated;
